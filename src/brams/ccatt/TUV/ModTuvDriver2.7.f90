  subroutine ctlOut(ia,iz,ja,jz,m1,kj,nReact,cMyNum,cTime,jjlabel)
    integer,intent(IN) :: ia,iz,ja,jz,m1,nReact,kj
    character(LEN=4), intent(IN) :: cMyNum
